local SKIP = { ID = true, TRICK = true, TRICKS = true, FLIP = true, GRAB = true, GRIND = true, GROUND = true }

--- Readable trick name; flags: engine stance bits (2 switch, 4 fakie). "" for non-tricks.
function SK.trick_name(id, flags)
    id = tostring(id or ""):gsub("^%s+", ""):gsub("%s+$", "")
    if id == "" then return "" end
    local name = NAMES[id]
    if name == nil then
        for _, w in ipairs({ "TYPE", "TERM", "DESC", "DESCRIPTION" }) do
            if id:find("^" .. w .. "_") or id:find("_" .. w .. "_") or id:find("_" .. w .. "$") then return "" end
        end
        local parts = {}
        for w in id:gmatch("[^_]+") do
            if not SKIP[w] then
                table.insert(parts, WORDS[w] or (w:match("^%d") and w or (w:sub(1, 1) .. w:sub(2):lower())))
            end
        end
        name = table.concat(parts, " ")
    end
    if name == "" then return "" end
    flags = flags or 0
    if (flags & 2) ~= 0 then name = "Switch " .. name
    elseif (flags & 4) ~= 0 and not name:find("Nollie") then name = "Fakie " .. name end
    return name
end
